"""experiments/analysis/results.py -- experiments/RESULTS.md from the analysis logs (Week 14, Ch. 40.1).

    python experiments/analysis/results.py

Every number comes from a committed analysis log (E1, E2, E3 and E5 test analyses, family_v1.json); nothing is
typed by hand. A table whose log does not exist yet says so. Synthetic data (Kestrel-Intents-v0) is labelled.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOGS = ROOT / "experiments" / "logs"
OUT = ROOT / "experiments" / "RESULTS.md"
NAME = {"clinc150": "CLINC150", "intents_v0": "Kestrel-Intents-v0 (synthetic)"}


def _f(x, fmt=".3f"):
    return "—" if x is None else format(x, fmt)


def _ci(c, key="diff", fmt="+.4f"):
    return f"{c[key]:{fmt}} [{c['ci95'][0]:{fmt}}, {c['ci95'][1]:{fmt}}]"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(r) + " |" for r in rows]


def table_r1(ds: str, r: dict) -> list[str]:
    title = f"### Table R1 · {NAME[ds]} · {r['n_items']} items ({r['n_latency_items']} timed), δ = {r['delta']:.4f}"
    if r.get("clusters"):
        title += f", bootstrap over {r['clusters']}"
    rows = [[s, f"{v['accuracy']:.3f}", f"{v['macro_f1']:.3f}", f"{v['coverage']:.3f}",
             f"{v['latency_ms']['mean']:.1f}", f"{v['latency_ms']['median']:.1f}", f"{v['latency_ms']['p95']:.1f}",
             _f(v["peak_rss_mib"], ".0f"), f"{v['tier4_share']:.1%}"] for s, v in r["systems"].items()]
    h = r["h1"]
    return [title, ""] + _table(["System", "Accuracy", "Macro-F1", "Coverage", "Mean ms", "Median ms", "p95 ms",
                                 "Peak RSS MiB", "Reaching Tier 4"], rows) + [
        "", f"H1 R3 vs tuned R0: Δacc {_ci(h['accuracy'])}, Δlat {_ci(h['latency'], 'diff_ms', '+.1f')} ms → "
            f"{h['outcome']} (intersection–union p {h['p_iut']:.2g})", ""]


def section_e2(ds: str, r: dict) -> list[str]:
    rows = [[t, str(v["n"]), f"{v['accuracy']:.3f}", f"{v['T']:.3f}", f"{v['ece_before']:.4f}", f"{v['ece_after']:.4f}",
             f"{v['risk_at_080_before']:.4f}", f"{v['risk_at_080_after']:.4f}"] for t, v in r["table_r2"].items()]
    h = r["h2"]
    out = [f"### Table R2 · {NAME[ds]}", ""] + _table(
        ["Tier", "n", "Accuracy", "T", "ECE before", "ECE after", "Risk@80% before", "Risk@80% after"], rows)
    out += ["", f"H2 risk@0.80: R2 {h['risk_at_080']['R2']:.4f}, R2c {h['risk_at_080']['R2c']:.4f}, "
                f"Δ {_ci(h['risk_at_080'])}; AURC R2 {h['aurc']['R2']:.4f}, R2c {h['aurc']['R2c']:.4f}, "
                f"Δ {_ci(h['aurc'])}"]
    if "h7b" in r:
        v = r["h7b"]["tier3"]
        out.append(f"H7b Tier-3 ECE en {v['ece_en']:.4f}, hi-en {v['ece_hi_en']:.4f}, gap {_ci(v, 'gap')}")
    return out + [""]


def section_e3(ds: str, r: dict) -> list[str]:
    rows = [[k, f"{v['accuracy']:.3f}", f"{v['cost_ms']['mean']:.1f}", f"{v['cost_ms']['p95']:.1f}",
             " / ".join(f"{v['tier_rate'][t]:.2f}" for t in ("1", "3", "4"))] for k, v in r["sets"].items()]
    h = r["h3"]
    return [f"### Table R3 · {NAME[ds]}", ""] + _table(["Tier set", "Accuracy", "Mean ms", "p95 ms", "Tier 1 / 3 / 4"],
                                                        rows) + [
        "", f"{h['a']} vs {h['b']}: Δacc {_ci(h['accuracy'])}, Δcost {_ci(h['cost'], 'diff_ms', '+.1f')} ms "
            f"({h['family']}). Area under the cost–accuracy curve: not computed (one frozen point per set).", ""]


def section_e5(e5: dict) -> list[str]:
    ms = lambda s, k, f=".3f": f"{s[k]['mean']:{f}} ± {s[k]['sd']:{f}}"  # noqa: E731
    rows = [[m, ms(s, "avg_accuracy"), ms(s, "avg_forgetting"), f"{s['bwt']['mean']:+.3f}",
             f"{s['seconds']['mean']:.1f}", f"{s['buffer_bytes']['mean']:.0f}"] for m, s in e5["table_r6"].items() if s]
    return ["### Table R6 · CLINC150", ""] + _table(
        ["Method", "Avg accuracy", "Avg forgetting", "BWT", "Update s", "Buffer bytes"], rows) + [""]


def section_family(family: dict) -> list[str]:
    g = lambda x: "—" if x is None else format(x, ".2g")  # noqa: E731
    rows = [[m["id"], g(m["p"]), g(m["p_holm"]), m["outcome"], m.get("source", "—")] for m in family["members"]]
    return _table(["Hypothesis", "p", "Holm p", "Outcome", "Source"], rows) + [
        "", "Members without a p (H4, H6) enter Holm with p = 1 until their amendment; an interim “supported” is "
            "final, an interim “inconclusive” may change.", ""]


def render(e1: dict, e2: dict, e3: dict, e5: dict | None, family: dict | None) -> str:
    md = ["# Kestrel results (PREREG v1)", "",
          "Generated by `experiments/analysis/results.py` from the committed analysis logs; every number comes from a "
          "log. Energy was not measured (RAPL is root-only on this machine).", ""]
    primary = e1.get("clinc150", {}).get("h1")
    md += ["## Primary hypothesis", "", f"H1 (primary, CLINC150): **{primary['outcome']}**" if primary
           else "H1 (primary, CLINC150): not run yet", ""]
    md += ["## E1 · routing policies", ""]
    md += [x for ds in ("clinc150", "intents_v0") if ds in e1 for x in table_r1(ds, e1[ds])] or ["E1: not run yet", ""]
    md += ["## E2 · calibration", ""]
    md += [x for ds, r in e2.items() for x in section_e2(ds, r)] or ["E2: not run yet", ""]
    md += ["## E3 · tier ablation", ""]
    md += [x for ds, r in e3.items() for x in section_e3(ds, r)] or ["E3: not run yet", ""]
    md += ["## E5 · forgetting", ""] + (section_e5(e5) if e5 else ["E5: not run yet", ""])
    md += ["## Secondary family (Holm, 13 members; ADR-029, ADR-032)", ""]
    md += section_family(family) if family else ["Family step: not run yet", ""]
    return "\n".join(md) + "\n"


def _load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def main() -> int:
    e1 = {ds: r for ds in NAME if (r := _load(LOGS / "E1" / f"analysis_{ds}_test.json"))}
    e2 = {ds: r for ds in NAME if (r := _load(LOGS / "E2" / f"analysis_{ds}_test.json"))}
    e3 = {ds: r for ds in NAME if (r := _load(LOGS / "E3" / f"analysis_{ds}_test.json"))}
    OUT.write_text(render(e1, e2, e3, _load(LOGS / "E5" / "analysis_test.json"), _load(LOGS / "family_v1.json")))
    print(f"-> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
